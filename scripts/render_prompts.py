"""Render the exact coordinator prompts for team review (addendum §4a.3).

Writes docs/PROMPTS_RENDERED.md: the system prompt and the round prompt at
round 1 and round 30 for the pilot cell (rho = 0, outcome-only, c = 5,
pi = 0.25, blind, points, neutral), plus the re-ask message. The history is
produced by a uniform-random stand-in on the first pilot seed's tapes, so the
notes field is empty; in a real run it holds the model's own notes.

This is the only writer of docs/PROMPTS_RENDERED.md (change 10). The doc
records the approval hash (sas/prompt_approval.py). Re-render after any
wording change, then re-approve by writing the hash to APPROVED_PROMPT_HASH or
the PREREGISTRATION §0 "Prompt hash" row.

  uv run scripts/render_prompts.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sas.coordinators import Uniform  # noqa: E402
from sas.env import Cell, run_episode  # noqa: E402
from sas.grid import load_experiment  # noqa: E402
from sas.prompt_approval import approval_hash, approved_hash, synthetic_observation  # noqa: E402
from sas.prompts import NOTES_MAX_CHARS, REASK, round_prompt, system_prompt  # noqa: E402
from sas.tapes import make_tapes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "PROMPTS_RENDERED.md"


def main():
    pilot = load_experiment(ROOT / "configs" / "pilot.yaml")
    cell = Cell(rho=0.0, feedback="outcome", c=5.0, pi=0.25)
    assert cell.cell_id in {c.cell_id for c in pilot.cells()}
    seed = pilot.seeds[0]
    seen = []

    class Rec(Uniform):
        def choose(self, obs):
            seen.append(obs)
            return super().choose(obs)

    run_episode(cell, make_tapes(seed, pilot.T), Rec(), pilot.T)
    fence = "~~~~"
    md = [
        "# Rendered coordinator prompts (for team review)",
        "",
        f"Generated by `scripts/render_prompts.py` for the pilot cell `{cell.cell_id}` "
        f"(blind, points framing, neutral tone), T = {pilot.T}, seed {seed}.",
        "",
        f"Approval hash: `{approval_hash()}`",
        "",
        "The approval hash covers every coordinator-visible text, including the variants below the "
        "pilot cell (qualitative framing, c = 15, reason lines, auto-assigned rows, task details). "
        "Live runs refuse to start unless it equals the approved hash in `APPROVED_PROMPT_HASH` or "
        "the `docs/PREREGISTRATION.md` §0 \"Prompt hash\" row "
        f"(currently approved: `{approved_hash() or 'none'}`).",
        "",
        "The history below comes from a uniform-random stand-in, so the notes field is empty. "
        f"In a real run it holds the coordinator's own notes from the previous round "
        f"(at most {NOTES_MAX_CHARS} characters). The system prompt is sent as the system message and "
        "the round prompt as the user message; nothing else is sent apart from model settings.",
        "",
        "## System prompt (system message, identical every round)",
        "", fence, system_prompt(cell, pilot.T), fence, "",
    ]
    for r in (1, 30):
        md += [f"## Round {r} prompt (user message)", "", fence, round_prompt(seen[r - 1], cell.framing), fence, ""]
    md += ["## Re-ask message (appended to the round prompt after an unusable reply; up to 2 times)",
           "", fence, REASK, fence, "",
           "## Every rendering branch (synthetic placeholders; covered by the approval hash)", "",
           "Rows for objected, completed, flagged and auto-assigned results, a reason-feedback line, "
           "notes, and task details (task-visible condition only).", "",
           fence, round_prompt(synthetic_observation(True), "points"), fence, "",
           "Qualitative framing (no numbers):", "",
           fence, system_prompt(Cell(rho=0.0, framing="qualitative"), pilot.T), fence, "",
           fence, round_prompt(synthetic_observation(False), "qualitative"), fence, ""]
    OUT.write_text("\n".join(md))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
